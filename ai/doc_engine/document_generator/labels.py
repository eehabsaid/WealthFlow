"""The fixed words of a generated guide (Table of Contents, Purpose, Steps, Generated, ...), looked up in the language's own
locale file (static/i18n/<lang>.json, keys "docgen_*"). English is the fallback for a key a locale lacks, never another language."""

FIXED = {   # context key -> (locale key, English text)
    "toc_title": ("docgen_toc", "Table of Contents"), "nav_title": ("docgen_nav_path", "Navigation Path"),
    "purpose_title": ("docgen_purpose", "Purpose"), "steps_title": ("docgen_steps", "Steps"),
    "tech_notes_title": ("docgen_tech", "Technical Details"), "figure_title": ("docgen_figure", "Figure"),
    "related_title": ("docgen_related", "Related Pages"), "lbl_app_name": ("docgen_lbl_app_name", "Application Name"),
    "lbl_guide_type": ("docgen_lbl_guide_type", "Guide Type"), "lbl_generated": ("docgen_lbl_generated", "Generated"),
    "lbl_language": ("docgen_lbl_language", "Language"), "lbl_theme": ("docgen_lbl_theme", "Theme"),
    "lbl_device": ("docgen_lbl_device", "Device"), "lbl_version": ("docgen_lbl_version", "Version"),
    "lbl_generated_by": ("docgen_lbl_generated_by", "Generated By"),
}
GUIDE_TYPES = {"user": ("docgen_user_guide", "User Guide"), "admin": ("docgen_admin_guide", "Admin Guide"),
               "technical": ("docgen_technical_guide", "Technical Guide")}


def fixed_labels(translations: dict) -> dict:
    return {ctx: translations.get(key) or english for ctx, (key, english) in FIXED.items()}


def guide_type_label(translations: dict, guide_type: str) -> str:
    key, english = GUIDE_TYPES.get(str(guide_type).lower(), ("", f"{str(guide_type).capitalize()} Guide"))
    return translations.get(key) or english
