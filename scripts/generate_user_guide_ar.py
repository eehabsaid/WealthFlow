def kebab_id(number: str, title: str) -> str:
    slug = re.sub(r"[^a-z0-9\u0600-\u06FF]+", "-", title.lower()).strip("-")
    return f"sec-{number.replace('.', '-')}-{slug}"


def esc(text: str) -> str:
    return html.escape(text, quote=True)


