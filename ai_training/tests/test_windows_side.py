class PreflightTest(SimpleTestCase):
    def folder(self, shards=True):
        d = tempfile.mkdtemp()
        open(os.path.join(d, "config.json"), "w").write("{}")
        if shards:
            open(os.path.join(d, "model-00001.safetensors"), "w").write("x")
        return d

    def test_base_checks_name_each_problem(self):
        c = cfg(base_model_dir=self.folder(False), work_dir=tempfile.mkdtemp(), min_free_gb=10 ** 9)
        with patch.object(preflight, "_ollama_has", return_value=False):
            bad = {x.name for x in preflight.failed(preflight.base_checks(c, 2, "m"))}
        self.assertEqual(bad, {"proven traces", "base model files", "free disk", "Ollama model"})

    def test_base_checks_pass_when_ready(self):
        c = cfg(base_model_dir=self.folder(), work_dir=tempfile.mkdtemp(), min_free_gb=0, min_traces=1)
        with patch.object(preflight, "_ollama_has", return_value=True):
            self.assertEqual(preflight.failed(preflight.base_checks(c, 5, "m")), [])

    def test_no_wsl_gives_the_install_command(self):
        with patch.object(wsl, "available", return_value=False):
            checks = preflight.wsl_checks(cfg())
        self.assertIn("wsl --install", checks[0].fix)

    def test_wsl_checks_gpu_tools_memory(self):
        answers = iter([(0, "GPU 0: NVIDIA GeForce RTX 5090 Laptop GPU"), (0, "cmake"), (0, "32")])
        with patch.object(wsl, "available", return_value=True), patch.object(wsl, "distros", return_value=["Ubuntu"]), \
                patch.object(wsl, "capture", side_effect=lambda *a, **k: next(answers)):
            gpu, tools, memory = preflight.wsl_checks(cfg(wsl_memory_gb=52))
        self.assertTrue(gpu.ok)
        self.assertFalse(tools.ok)
        self.assertIn("apt-get install", tools.fix)
        self.assertFalse(memory.ok)
        self.assertIn("memory=52GB", memory.fix)


class OllamaStageTest(SimpleTestCase):
    def test_modelfile_keeps_template_and_settings_with_one_from(self):
        text = ollama_stage.rewrite_modelfile(MODELFILE, r"D:\w\m.gguf")
        self.assertEqual([l for l in text.splitlines() if l.startswith("FROM ")], [r"FROM D:\w\m.gguf", "FROM inside a template line must stay"])
        self.assertIn("PARAMETER num_ctx 153600", text)
        self.assertNotIn("sha256", text)

    def test_new_name_never_doubles_the_suffix(self):
        self.assertEqual(ollama_stage.new_name("qwen3.8:27b-150k", "-agent"), "qwen3.8:27b-150k-agent")
        self.assertEqual(ollama_stage.new_name("qwen3.8:27b-150k-agent", "-agent"), "qwen3.8:27b-150k-agent")

    def test_register_creates_the_model_from_the_rewritten_file(self):
        folder, calls = tempfile.mkdtemp(), []

        def fake_run(cmd, **kw):
            calls.append(cmd)
            return SimpleNamespace(returncode=0, stdout=MODELFILE.encode() if "--modelfile" in cmd else b"success", stderr=b"")

        with patch("ai_training.services.ollama_stage.subprocess.run", side_effect=fake_run):
            self.assertTrue(ollama_stage.register("qwen3.8:27b-150k", r"D:\w\m.gguf", "qwen3.8:27b-150k-agent", folder, lambda line: None))
        self.assertEqual(calls[1][:3], ["ollama", "create", "qwen3.8:27b-150k-agent"])
        self.assertIn(r"FROM D:\w\m.gguf", open(os.path.join(folder, "Modelfile.new")).read())

    def test_failure_to_read_the_current_model_is_reported(self):
        bad = SimpleNamespace(returncode=1, stdout=b"", stderr=b"not found")
        with patch("ai_training.services.ollama_stage.subprocess.run", return_value=bad):
            self.assertFalse(ollama_stage.register("m", "g", "n", tempfile.mkdtemp(), lambda line: None))
