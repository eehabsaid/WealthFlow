"""Income (salary entry) actions: edit and delete only. Salary rows are generated every month by the Salary screen,
so the assistant changes or removes existing ones; it never invents a new month."""

from __future__ import annotations

from decimal import Decimal

from core.models import SalaryEntry
from core.services.salary.salary_service import SalaryService

from .common import ActionError, changed_rows, money, one_of

FIELDS = ("expected", "paid", "bonus")


def _row(e: SalaryEntry) -> dict:
    return {"id": e.id, "company": e.company.name, "year": e.year, "month": e.month, "expected": str(e.expected), "paid": str(e.paid), "bonus": str(e.bonus), "notes": e.notes}


def find(user, target: dict) -> SalaryEntry:
    qs = SalaryEntry.objects.filter(company__owner=user).select_related("company")
    if target.get("id"):
        qs = qs.filter(pk=target["id"])
    elif target.get("year") and target.get("month"):
        qs = qs.filter(year=int(target["year"]), month__iexact=str(target["month"]).strip())
    else:
        raise ActionError("say which salary entry: target.id, or target.year and target.month (month name as in the Salary screen)")
    rows = [{"id": e.id, "label": f"#{e.id} {e.company.name} {e.month} {e.year}"} for e in qs[:6]]
    return qs.get(pk=one_of(rows, "salary entry")["id"])


def propose(user, op: str, target: dict, values: dict) -> dict:
    if op == "add":
        raise ActionError("salary entries are generated by the Salary screen each month; the assistant can only edit or delete an existing one")
    entry = find(user, target)
    current = _row(entry)
    if op == "delete":
        return {"record": "income", "op": "delete", "params": {"id": entry.id}, "rows": [{"label": k, "value": str(v)} for k, v in current.items() if k != "id" and v != ""]}
    clean = {}
    for key in FIELDS:
        if key in values:
            clean[key] = str(money(values[key], key) if Decimal(str(values[key]) or 0) != 0 else Decimal("0.00"))
    if "notes" in values:
        clean["notes"] = " ".join(str(values["notes"] or "").split())[:500]
    rows = changed_rows(current, clean)
    if not rows:
        raise ActionError("nothing would change; ask the user what to change")
    return {"record": "income", "op": "edit", "params": {"id": entry.id, "data": clean}, "rows": rows}


def execute(user, op: str, params: dict) -> str:
    try:
        if op == "delete":
            SalaryService().delete_salary(params["id"], user)
            return f"Salary entry #{params['id']} deleted."
        SalaryService().update_salary(params["id"], params["data"], user)
        return f"Salary entry #{params['id']} updated."
    except SalaryEntry.DoesNotExist:
        raise ActionError("That salary entry no longer exists.") from None
